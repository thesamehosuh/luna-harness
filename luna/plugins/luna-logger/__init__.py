"""luna-logger — tokenless indexer.

The gateway is the sole Telegram poller. With ``observe_unmentioned_group_messages`` enabled it
writes every group message into a shared observe session in ``state.db``. This plugin tails that
transcript (read-only) into the derived ``luna-state.db``: messages, identity registry, reply map.

There is no bot token here. The poller starts lazily on the first gateway dispatch (so it never runs
in CLI-only processes) and is single-instance.

Config (env, all optional):
  LUNA_LOGGER_ENABLED   "true"
  LUNA_LOGGER_POLL      "2"       seconds between passes
  LUNA_LOGGER_BATCH     "500"
  LUNA_STATE_DB         "$HERMES_HOME/state.db"
  LUNA_INDEX_DB         "$HERMES_HOME/luna-state.db"
  LUNA_PEER_PREFIX      "telegram_"
"""

from __future__ import annotations

from luna_core.runtime import home as runtime_home, getenv

import logging
import os
import sqlite3
import sys
import threading
import time
from pathlib import Path
from typing import Any, Optional

_LIB = Path(__file__).resolve().parents[2] / "lib"
if str(_LIB) not in sys.path:
    sys.path.insert(0, str(_LIB))

from luna_core import config_read  # noqa: E402
from luna_core import db as luna_db  # noqa: E402
from luna_core.identity import IdentityRegistry  # noqa: E402
from luna_core import retention  # noqa: E402
from luna_core.indexer import index_observe_transcript  # noqa: E402

log = logging.getLogger("luna-logger")

_LOCK = threading.Lock()
_THREAD: Optional[threading.Thread] = None
_STOP = threading.Event()


def _flag(name: str, default: bool) -> bool:
    raw = getenv(name)
    if raw is None or not raw.strip():
        return default
    return raw.strip().lower() not in {"0", "false", "no", "off"}


def _num(name: str, default: int) -> int:
    try:
        return int(str(getenv(name, "")).strip() or default)
    except (TypeError, ValueError):
        return default


def _poll_seconds() -> int:
    """Index cadence. This is the first latency term in the wake path (observe -> index -> ambient),
    so keep it tight: an index pass is a cheap watermark scan and only writes new rows."""
    default = 2
    try:
        value = config_read.section("luna", "logger", "poll_seconds", default=default)
        default = int(value)
    except Exception:
        pass
    return max(1, _num("LUNA_LOGGER_POLL", default))


def _chat_id() -> str:
    configured = str(getenv("LUNA_CHAT_ID") or "").strip()
    if configured:
        return configured
    try:
        configured = str(config_read.section("luna", "room", "chat_id", default="") or "").strip()
        if configured:
            return configured
        allowed = config_read.section("telegram", "group_allowed_chats")
        if isinstance(allowed, list) and len(allowed) == 1:
            return str(allowed[0]).strip()
        return ""
    except Exception:
        return ""


def _sync_honcho_default() -> bool:
    try:
        return bool(config_read.section("luna", "logger", "sync_honcho", default=True))
    except Exception:
        return True


def _room_session() -> str:
    raw = str(getenv("LUNA_ROOM_SESSION_KEY") or "").strip()
    if raw:
        return raw
    chat = _chat_id()
    return f"agent:main:telegram:group:{chat}" if chat else ""


def _honcho_json_path() -> Path:
    raw = str(getenv("LUNA_HONCHO_JSON") or "").strip()
    home = runtime_home()
    return Path(os.path.expandvars(raw)).expanduser() if raw else home / "honcho.json"


def sync_alias_map(index_conn) -> int:
    """Keep ``honcho.json``'s ``userPeerAliases`` fresh from the registry (best-effort).

    Without this the map is only regenerated by a manual sync from the People page, so a member who
    appeared since the last manual run falls back to upstream's own peer-id derivation — a
    different suffix rule than ``sanitize_peer_id`` — and the same human ends up as two Honcho
    peers. The indexer is the component that learns new identities, so it is the one that
    refreshes the map. No-op writes are skipped (mtime-keyed caches upstream).
    """
    try:
        from luna_core.identity import IdentityRegistry, apply_overrides
        from luna_core.peers import update_honcho_aliases

        registry = IdentityRegistry(index_conn, prefix=getenv("LUNA_PEER_PREFIX", "telegram_"))
        apply_overrides(registry)
        return update_honcho_aliases(_honcho_json_path(), registry)
    except Exception:
        log.debug("[luna-logger] alias map refresh failed", exc_info=True)
        return 0


def sync_honcho_room(index_conn) -> int:
    """Write indexed messages into each public group session, per author/topic.

    Best-effort and idempotent (dedup by message_id). Returns messages written; 0 on any failure
    (e.g. Honcho down, SDK missing) — never raises.
    """
    if config_read.section("luna", "setup", "memory", default="enabled") != "enabled":
        return 0
    if not _flag("LUNA_LOGGER_SYNC_HONCHO", _sync_honcho_default()):
        return 0
    from plugins.memory.honcho.client import HonchoClientConfig
    memory_config = HonchoClientConfig.from_global_config()
    if not memory_config.enabled or not memory_config.save_messages:
        return 0
    from luna_core.managed_memory import restore
    restore()
    primary_chat = _chat_id()
    allowed = {str(chat) for chat in config_read.section("telegram", "group_allowed_chats", default=[]) or []}
    if primary_chat:
        allowed.add(primary_chat)
    rooms = [str(row[0]) for row in index_conn.execute(
        "SELECT DISTINCT chat_id FROM messages ORDER BY chat_id")
        if str(row[0]) in allowed and str(row[0]).startswith("-")]
    if not rooms:
        return 0
    try:
        from luna_core.honcho import HonchoStore, backfill_room, public_room_session

        from luna_core.honcho import connection_settings
        store = HonchoStore(**connection_settings())
        written = 0
        limit = max(1, _num("LUNA_LOGGER_HONCHO_LIMIT", 50) // len(rooms))
        for chat_id in rooms:
            result = backfill_room(store, index_conn, chat_id=chat_id,
                room_session=public_room_session("telegram", chat_id), limit=limit)
            written += result.written
            if result.errors:
                log.debug("[luna-logger] honcho room errors: %s", result.errors[:3])
        if written:
            log.info("[luna-logger] synced %d message(s) to scoped Honcho rooms", written)
        return written
    except Exception:
        log.debug("[luna-logger] honcho room sync skipped", exc_info=True)
        return 0


def _home() -> Path:
    return runtime_home()


def _state_db_path() -> Path:
    raw = str(getenv("LUNA_STATE_DB") or "").strip()
    return Path(os.path.expandvars(raw)).expanduser() if raw else _home() / "state.db"


def _index_db_path() -> Path:
    raw = str(getenv("LUNA_INDEX_DB") or "").strip()
    return Path(os.path.expandvars(raw)).expanduser() if raw else _home() / "luna-state.db"


def index_once() -> int:
    """One indexing pass. Returns rows indexed. Never raises (returns 0 on failure)."""
    state_path = _state_db_path()
    if not state_path.exists():
        log.debug("[luna-logger] state.db not present yet: %s", state_path)
        if _index_db_path().exists():
            conn = luna_db.connect(_index_db_path())
            try:
                luna_db.init_db(conn)
                sync_honcho_room(conn)
            finally:
                conn.close()
        return 0
    state_conn = None
    try:
        state_conn = sqlite3.connect(f"file:{state_path}?mode=ro", uri=True, timeout=2.0)
        state_conn.row_factory = sqlite3.Row
        index_conn = luna_db.connect(_index_db_path())
        try:
            luna_db.init_db(index_conn)
            registry = IdentityRegistry(index_conn, prefix=getenv("LUNA_PEER_PREFIX", "telegram_"))
            n = index_observe_transcript(
                state_conn, index_conn, registry=registry, batch=_num("LUNA_LOGGER_BATCH", 500)
            )
            if n:
                log.info("[luna-logger] indexed %d observed message(s)", n)
                # New members may have been learned this pass; keep the Honcho alias map fresh so
                # upstream resolves them to registry peers (one human, one peer).
                sync_alias_map(index_conn)
                # Keep the Honcho room session current (per-author, idempotent, best-effort).
            sync_honcho_room(index_conn)
            return n
        finally:
            index_conn.close()
    except Exception:
        log.warning("[luna-logger] indexing pass failed", exc_info=True)
        return 0
    finally:
        if state_conn is not None:
            state_conn.close()


def _retention_interval_seconds() -> int:
    """How often the retention pass runs. Deliberately coarse: pruning is housekeeping, not a
    wake-latency concern, and it must never compete with indexing for the SQLite write lock.

    Reads env first, then ``luna.data.auto_prune_interval_minutes`` from config — the dashboard
    exposes that key, so honouring only the env var would make the UI field gate nothing.
    """
    return retention.auto_prune_interval_seconds(60)


def _enforce_retention() -> None:
    """Apply the retention window. Best-effort: never raises, never blocks indexing."""
    try:
        summary = retention.enforce()
    except Exception:
        log.warning("[luna-logger] retention pass failed", exc_info=True)
        return
    # Counts only — the summary never contains message text, so this is safe to log.
    skipped = summary.get("skipped")
    if skipped:
        log.debug("[luna-logger] retention pass skipped: %s", skipped)
        return
    # A failed sub-pass (e.g. "database is locked" past busy_timeout) must be visible: logging the
    # summary at debug meant a month of failing prunes — and a growing transcript — showed nothing.
    failed = [f"{k}={v}" for k, v in summary.items() if isinstance(v, dict) and v.get("failed")]
    if failed:
        log.warning("[luna-logger] retention pass partially failed: %s", ", ".join(failed))
    else:
        log.debug("[luna-logger] retention pass applied: %s", summary)


def _loop(poll_seconds: int) -> None:
    interval = _retention_interval_seconds()
    # Seed the clock so the FIRST pass runs on this iteration. Starting at "now" instead meant a
    # process that lived less than one interval (restarts, deploys, config edits) never pruned.
    last_prune = time.monotonic() - interval
    while not _STOP.is_set():
        index_once()
        now = time.monotonic()
        if now - last_prune >= interval:
            last_prune = now
            _enforce_retention()
        _STOP.wait(poll_seconds)


def _ensure_thread() -> None:
    global _THREAD
    with _LOCK:
        if _THREAD is not None and _THREAD.is_alive():
            return
        _STOP.clear()
        from luna_core.runtime import worker_context
        context = worker_context()
        _THREAD = threading.Thread(
            target=context.run, args=(_loop, _poll_seconds()),
            name="luna-logger", daemon=True,
        )
        _THREAD.start()
        log.info("[luna-logger] indexer thread started")


def _on_pre_gateway_dispatch(event: Any = None, gateway: Any = None, **kwargs: Any) -> None:
    """Start the indexer lazily in gateway context (never in CLI-only processes)."""
    if not _flag("LUNA_LOGGER_ENABLED", True):
        return None
    try:
        _ensure_thread()
    except Exception:
        log.warning("[luna-logger] could not start indexer", exc_info=True)
    return None


def _in_gateway_process() -> bool:
    """True when this process is the messaging gateway (not the CLI)."""
    if getenv("_HERMES_GATEWAY") == "1":
        return True
    argv = " ".join(sys.argv)
    return "gateway" in argv and " run" in f" {argv}"


def register(ctx) -> None:
    ctx.register_hook("pre_gateway_dispatch", _on_pre_gateway_dispatch)
    # Start at gateway boot; a lazy start on pre_gateway_dispatch never runs if nothing triggers.
    in_gateway = _in_gateway_process()
    log.info("[luna-logger] register: gateway=%s argv=%s", in_gateway, sys.argv[:4])
    if in_gateway:
        try:
            _ensure_thread()
        except Exception:
            log.warning("[luna-logger] boot start failed", exc_info=True)
